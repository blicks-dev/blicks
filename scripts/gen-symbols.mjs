#!/usr/bin/env node
/**
 * Generates the Material Symbols Rounded glyphs the Blicks UI panels draw, as inline SVG path data.
 *
 * Output: resources/framework/inspector-v2/symbols.gen.ts
 *
 * Inline SVG rather than the icon font: a plugin may not load remote fonts, and a bundled font
 * draws its ligature names as text until it loads. These are the same glyphs (weight 400, fill 0,
 * Rounded, 24px) from Google's material-design-icons repository, pinned below. Apache-2.0, see
 * licenses.txt.
 *
 * Not part of the build: it fetches, so it runs by hand when the icon list changes —
 * `node scripts/gen-symbols.mjs` — and the generated file is committed.
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );
const OUT = resolve( ROOT, 'resources/framework/inspector-v2/symbols.gen.ts' );
// A commit of google/material-design-icons; the npm mirrors drop renamed glyphs (auto_awesome).
const REF = '10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7';
const url = ( name ) => `https://raw.githubusercontent.com/google/material-design-icons/${ REF }/symbols/web/${ name }/materialsymbolsrounded/${ name }_24px.svg`;

/** Every glyph the design panel and the Layers Find use. One meaning per glyph, as the README sets. */
const NAMES = [
	'ads_click', 'align_horizontal_center', 'align_horizontal_left', 'align_horizontal_right', 'align_justify_center',
	'align_justify_flex_end', 'align_justify_flex_start', 'align_justify_space_between', 'animation', 'arrow_selector_tool',
	'aspect_ratio', 'auto_awesome', 'blur_on', 'border_bottom', 'border_left', 'border_right', 'border_style', 'border_top',
	'check_box_outline_blank', 'chevron_right', 'close', 'code', 'content_cut', 'crop_square', 'dashboard', 'desktop_windows',
	'east', 'expand_less', 'expand_more', 'filter_b_and_w', 'flip_to_back', 'flip_to_front', 'format_align_center',
	'format_align_justify', 'format_align_left', 'format_align_right', 'format_color_fill', 'format_letter_spacing',
	'format_line_spacing', 'format_quote', 'format_size', 'gradient', 'grid_view', 'horizontal_distribute', 'hourglass_empty',
	'image', 'keyboard', 'light_mode', 'line_curve', 'motion_photos_off', 'north', 'north_east', 'north_west', 'notes',
	'opacity', 'open_with', 'padding', 'palette', 'play_arrow', 'rotate_right', 'search', 'settings', 'shadow', 'smart_button',
	'smartphone', 'south', 'south_east', 'south_west', 'swipe_up', 'swipe_vertical', 'tablet_mac', 'text_fields', 'timer',
	'title', 'touch_app', 'tune', 'vertical_distribute', 'view_agenda', 'view_column', 'view_week', 'warning', 'west', 'width',
	'zoom_in', 'image_aspect_ratio', 'list', 'format_list_numbered', 'bolt',
	// The block inspector's section heads and its More tab.
	'edit_note', 'category', 'link', 'accessibility_new', 'devices', 'more_horiz', 'database', 'send', 'rule', 'checklist', 'view_carousel', 'format_paragraph', 'layers', 'shield', 'mark_email_read', 'last_page', 'inbox',
];

const out = {};
for ( const name of NAMES ) {
	const res = await fetch( url( name ) );
	if ( ! res.ok ) {
		console.error( `${ name }: ${ res.status }` );
		process.exit( 1 );
	}
	const svg = await res.text();
	const paths = [ ...svg.matchAll( /\sd="([^"]+)"/g ) ].map( ( m ) => m[ 1 ] );
	// Older glyphs are drawn on a 24-unit grid, newer ones on 960 with the origin at the bottom.
	const viewBox = /viewBox="([^"]+)"/.exec( svg )?.[ 1 ] ?? '0 0 24 24';
	if ( ! paths.length ) {
		console.error( `${ name }: unexpected SVG` );
		process.exit( 1 );
	}
	out[ name ] = [ viewBox, paths.join( '' ) ];
}

const body = Object.entries( out ).map( ( [ k, [ box, d ] ] ) => `\t${ k }: [ '${ box }', '${ d }' ],` ).join( '\n' );
writeFileSync(
	OUT,
	`// Generated by scripts/gen-symbols.mjs from google/material-design-icons@${ REF } (Rounded). Do not edit.\n` +
		`// Material Symbols © Google, Apache License 2.0 — see licenses.txt.\n` +
		`// Each entry is [ viewBox, path ].\n\n` +
		`export const SYMBOLS: Record< string, readonly [ string, string ] > = {\n${ body }\n};\n`
);
console.log( `symbols.gen.ts: ${ NAMES.length } glyphs` );
