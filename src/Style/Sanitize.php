<?php
/**
 * Strict validation for user-supplied custom HTML attributes and style output.
 *
 * @package Blicks
 */

declare(strict_types=1);

namespace Blicks\Style;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Strict validation/sanitization for the Advanced-tab custom HTML attributes, plus the guard that
 * keeps generated CSS from breaking out of a `<style>` element. **Authoritative front-end gate.**
 * Mirror of `resources/framework/sanitize.ts` — keep the two byte-compatible
 * (parity: tests/Unit/Style/SanitizeTest.php ⇄ sanitize.test.ts).
 */
final class Sanitize {

	private const ATTR_NAME_RE   = '/^(?:data-[a-z0-9-]+|aria-[a-z-]+|role|title|id|lang|dir|tabindex)$/';
	private const CONTROL_CHARS  = '/[\x00-\x1F\x7F]/';
	private const SCRIPT_SCHEME  = '/(?:javascript|vbscript)\s*:/i';
	private const ATTR_VALUE_MAX = 500;

	/** Normalised (lowercased) attribute name, or null if disallowed. */
	public static function attrName( string $name ): ?string {
		$n = strtolower( trim( $name ) );
		return 1 === preg_match( self::ATTR_NAME_RE, $n ) ? $n : null;
	}

	/**
	 * Per-name value rule for the few attributes the generic sanitizer cannot judge.
	 * `tabindex` is the only one: the browser ignores a non-integer, so a value that
	 * fails here is dropped rather than written out as dead markup.
	 */
	private const ATTR_VALUE_RE = [
		'tabindex' => '/^-?\\d+$/',
	];

	/**
	 * Sanitize a value in the context of its attribute name. Null when the name carries
	 * a value rule the value does not satisfy.
	 */
	public static function attrValueFor( string $name, string $value ): ?string {
		$v   = self::attrValue( $value );
		$rule = self::ATTR_VALUE_RE[ $name ] ?? null;
		if ( null !== $rule && 1 !== preg_match( $rule, $v ) ) {
			return null;
		}
		return $v;
	}

	/** Strip control chars + dangerous URL schemes, cap length. */
	public static function attrValue( string $value ): string {
		$v = (string) preg_replace( self::CONTROL_CHARS, '', $value );
		$v = (string) preg_replace( self::SCRIPT_SCHEME, '', $v );
		$v = trim( $v );
		if ( mb_strlen( $v ) > self::ATTR_VALUE_MAX ) {
			$v = mb_substr( $v, 0, self::ATTR_VALUE_MAX );
		}
		return $v;
	}

	/**
	 * Validate a list of `{name,value}` rows → name => value (valid only, last write wins).
	 *
	 * @param mixed $list
	 * @return array<string,string>
	 */
	public static function attributes( $list ): array {
		if ( ! is_array( $list ) ) {
			return [];
		}
		$out = [];
		foreach ( $list as $item ) {
			if ( ! is_array( $item ) ) {
				continue;
			}
			$name = self::attrName( (string) ( $item['name'] ?? '' ) );
			if ( null === $name ) {
				continue;
			}
			$value = self::attrValueFor( $name, (string) ( $item['value'] ?? '' ) );
			if ( null === $value ) {
				continue;
			}
			$out[ $name ] = $value;
		}
		return $out;
	}

	/**
	 * Keep generated CSS safe inside a `<style>` element without HTML-escaping valid selectors.
	 * The payload is machine-generated by the style engine, but it interpolates user-entered
	 * token values, so a stray `</style` must never be able to close the element.
	 */
	public static function styleTagContent( string $css ): string {
		return (string) preg_replace( '/<\/\s*style/i', '<\/style', $css );
	}
}
